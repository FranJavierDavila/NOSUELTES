# ── TOC automático (TocDocTemplate + multiBuild) ──────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            # El pie renumera: RL página 1 = índice (romano i), contenido = arábigo
            # (doc.page - 1). El TOC debe mostrar EXACTAMENTE lo que pinta el pie.
            shown = self.page - 1 if self.page > 1 else self.page
            self.notify("TOCEntry", (level, text, shown, key))


def add_heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1_block(text, first_para):
    return [CondPageBreak(H1_ORPHAN),
            KeepTogether([add_heading(text, h1, 0), first_para])]


def safe_keep(elements):
    total = 0
    for el in elements:
        w, hh = el.wrap(AVAIL_W, PAGE_H)
        total += hh
    if total <= A4[1] * 0.4:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def tabla(data, ratios, header=True):
    widths = [r * AVAIL_W * 0.96 for r in ratios]
    assert sum(widths) <= AVAIL_W + 0.5
    rows = []
    for i, row in enumerate(data):
        st = th if (header and i == 0) else (td if i % 2 == 1 or not header else td)
        rows.append([Paragraph(str(cell), th if (header and i == 0) else td) for cell in row])
    t = Table(rows, colWidths=widths, hAlign="CENTER", repeatRows=1 if header else 0)
    style = [
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR))
        for i in range(1, len(data)):
            style.append(("BACKGROUND", (0, i), (-1, i),
                          TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def callout(num, label):
    c = Table([[Paragraph("<b>%s</b>" % num, stat_big)],
               [Paragraph(label, stat_lbl)]], colWidths=[190])
    c.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 1, ACCENT),
        ("TOPPADDING", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return c


def callout_row(items):
    cells = [callout(n, l) for n, l in items]
    t = Table([cells], colWidths=[AVAIL_W * 0.96 / len(cells)] * len(cells), hAlign="CENTER")
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("ALIGN", (0, 0), (-1, -1), "CENTER")]))
    return t


